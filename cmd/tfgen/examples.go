package main

import (
	"fmt"
	"slices"
	"strings"

	"github.com/appvia/terraform-provider-wayfinder/internal/manifest"
)

func exampleFiles(k manifest.Kind) map[string]string {
	name := typeName(k)
	var identity strings.Builder
	identity.WriteString("  name = \"example\"\n")
	if slices.Contains(k.Scopes, "workspace") || slices.Contains(k.Scopes, "environment") {
		identity.WriteString("  workspace = \"example\"\n")
	}
	if len(k.Scopes) == 1 && k.Scopes[0] == "environment" {
		identity.WriteString("  environment = \"example\"\n")
	}
	if k.Versioned {
		identity.WriteString("  version = \"1.0.0\"\n")
	}
	var required strings.Builder
	for _, jsonName := range propertyNames(k.Spec) {
		f := k.Spec.Properties[jsonName]
		if !f.Required || (f.Computed && !f.Sensitive) {
			continue
		}
		if f.Sensitive {
			required.WriteString("  # Replace this write-only placeholder with an ephemeral secret.\n")
		}
		fmt.Fprintf(&required, "  %s = %s\n", fieldName(jsonName, f, true), placeholder(f))
	}
	var imports strings.Builder
	imports.WriteString("#!/bin/sh\n# Code generated by tfgen. DO NOT EDIT.\nset -eu\n")
	for _, scope := range k.Scopes {
		id := "example"
		switch scope {
		case "workspace":
			id = "example-workspace/example"
		case "environment":
			id = "example-workspace/example-environment/example"
		}
		if k.Versioned {
			id += "@1.0.0"
		}
		fmt.Fprintf(&imports, "# %s scope\nterraform import %s.example '%s'\n", scope, name, id)
	}
	return map[string]string{
		"resources/" + name + "/resource.tf":       header + fmt.Sprintf("resource %q \"example\" {\n%s%s}\n", name, identity.String(), required.String()),
		"resources/" + name + "/import.sh":         imports.String(),
		"data-sources/" + name + "/data-source.tf": header + fmt.Sprintf("data %q \"example\" {\n%s}\n", name, identity.String()),
	}
}

func placeholder(f *manifest.Field) string {
	if len(f.Enum) > 0 {
		return fmt.Sprintf("%q", f.Enum[0])
	}
	switch f.Type {
	case "string":
		return `"example"`
	case "json":
		return "jsonencode({})"
	case "boolean":
		return "true"
	case "integer", "number":
		return "1"
	case "array":
		return "[" + placeholder(f.Items) + "]"
	case "map":
		return "{ example = " + placeholder(f.Values) + " }"
	case "object":
		var b strings.Builder
		b.WriteString("{\n")
		for _, name := range propertyNames(f) {
			child := f.Properties[name]
			if !child.Required || (child.Computed && !child.Sensitive) {
				continue
			}
			if child.Sensitive {
				b.WriteString("    # Replace this write-only placeholder with an ephemeral secret.\n")
			}
			fmt.Fprintf(&b, "    %s = %s\n", fieldName(name, child, false), placeholder(child))
		}
		b.WriteString("  }")
		return b.String()
	default:
		return "null"
	}
}
