// createResources parses the swagger and creates the resources along side adding
// the manual written resources
func createResources(ctx context.Context,
	config Config,
	definitions *loads.Document) (map[string]*schema.Resource, error) {

	// @step: parse the swagger spec and generate resource types
	// from the swagger spec
	list, err := ParseForResources(ParserOptions{
		Document:         definitions,
		IncludeResources: config.IncludeResources,
		PathPrefixes:     []string{"/api/v1alpha1/"},
		SkippedResources: config.SkippedResources,
	})
	if err != nil {
		return nil, err
	}

	resources := make(map[string]*schema.Resource)

	for name, resource := range list {
		log.Printf("adding resource: %s, apigroup: %s", name, resource.APIVersion)

		resources[name] = &schema.Resource{
			CreateContext: createResourceHandler(resource),
			DeleteContext: deleteResourceHandler(resource),
			Description:   resource.Description,
			ReadContext:   readResourceHandler(resource),
			Schema:        resource.Schema,
			UpdateContext: updateResourceHandler(resource),
			Timeouts: &schema.ResourceTimeout{
				Default: schema.DefaultTimeout(10 * time.Minute),
			},
		}
	}

	// @step: add the manual resources into the schema
	resources["wayfinder_workspace"] = makeWorkspaceResource()
	resources["wayfinder_user"] = makeUserResource()

	return resources, nil
}
