// New creates and returns a terraform provider
func New(config Config) (plugin.ProviderFunc, error) {
	ctx := context.Background()

	// @step: we need to parse the swagger configuration
	data, err := io.ReadAll(config.SwaggerSpec)
	if err != nil {
		return nil, err
	}
	document, err := openapi.Analyzed(json.RawMessage(data), "")
	if err != nil {
		return nil, err
	}

	// @step: autogenerated the terraform resources and add any manual resources
	resources, err := createResources(ctx, config, document)
	if err != nil {
		return nil, err
	}
	// @step: create the data sources from the swagger spec and add any manual data sources
	dataSources, err := createDataSources(ctx, config, document)
	if err != nil {
		return nil, err
	}

	return func() *schema.Provider {
		provider := &schema.Provider{
			ConfigureContextFunc: configure,
			ResourcesMap:         resources,
			DataSourcesMap:       dataSources,
			Schema: map[string]*schema.Schema{
				"config_file": {
					Type:        schema.TypeString,
					DefaultFunc: schema.EnvDefaultFunc("WAYFINDER_CONFIG", path.Join(os.Getenv("HOME"), ".wayfinder", "config")),
					Description: "The path to the wayfinder configuration file.",
					Optional:    true,
				},
				"endpoint": {
					Type:        schema.TypeString,
					DefaultFunc: schema.EnvDefaultFunc("WAYFINDER_ENDPOINT", "http://localhost:8080"),
					Description: "The URL for the Wayfinder API endpoint (e.g https://api.example.com).",
					Optional:    true,
				},
				"refresh_token": {
					Type:        schema.TypeString,
					DefaultFunc: schema.EnvDefaultFunc("WAYFINDER_TOKEN", ""),
					Description: "The refresh robot token used to authenticate to the Wayfinder instance.",
					Optional:    true,
					Sensitive:   true,
				},
			},
		}

		return provider
	}, nil
}

